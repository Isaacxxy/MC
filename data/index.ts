const generateSizes = (
  basePrice: number,
  basePoints: number,
  baseSugar: number
) => ({
  small: {
    price: basePrice * 0.8,
    stock: 100,
    points: Math.round(basePoints * 0.8),
    sugarContent: Math.round(baseSugar * 0.8),
  },
  medium: {
    price: basePrice,
    stock: 100,
    points: basePoints,
    sugarContent: baseSugar,
  },
  large: {
    price: basePrice * 1.2,
    stock: 100,
    points: Math.round(basePoints * 1.2),
    sugarContent: Math.round(baseSugar * 1.2),
  },
});

